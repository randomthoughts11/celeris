function generateSnapshots(companyId: string, base: CompanyMetrics): PerformanceSnapshot[] {
  const snapshots: PerformanceSnapshot[] = [];
  for (let i = 29; i >= 0; i--) {
    const date = new Date();
    date.setDate(date.getDate() - i);
    const variance = 0.85 + Math.random() * 0.3;
    snapshots.push({
      id: `snap-${companyId}-${i}`,
      company_id: companyId,
      snapshot_date: date.toISOString().split("T")[0],
      revenue: Math.round((base.revenue / 30) * variance),
      leads: Math.round((base.leads_count / 30) * variance),
      conversions: Math.round((base.conversions / 30) * variance),
      ad_spend: Math.round((base.ad_spend / 30) * variance),
      roas: base.roas * (0.9 + Math.random() * 0.2),
    });
  }
  return snapshots;
}

