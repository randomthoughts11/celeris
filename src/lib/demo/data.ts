export const demoStore = {
  companies,
  insights,
  googleCampaigns,
  metaCampaigns,
  leads,
  leadActivities,
  tasks,
  socialPosts,
  socialMetrics,
  calls,
  getCompanyBySlug(slug: string) {
    return companies.find((c) => c.slug === slug) ?? null;
  },
  getCompanyById(id: string) {
    return companies.find((c) => c.id === id) ?? null;
  },
  getSnapshots(companyId: string) {
    const company = companies.find((c) => c.id === companyId);
    if (!company?.metrics) return [];
    return generateSnapshots(companyId, company.metrics);
  },
  getInsights(companyId: string) {
    return insights.filter((i) => i.company_id === companyId && !i.is_dismissed);
  },
  getGoogleCampaigns(companyId: string) {
    return googleCampaigns.filter((c) => c.company_id === companyId);
  },
  getMetaCampaigns(companyId: string) {
    return metaCampaigns.filter((c) => c.company_id === companyId);
  },
  getLeads(companyId: string) {
    return leads.filter((l) => l.company_id === companyId);
  },
  getLeadActivities(leadId: string) {
    return leadActivities.filter((a) => a.lead_id === leadId);
  },
  getTasks(companyId: string) {
    return tasks.filter((t) => t.company_id === companyId);
  },
  getSocialPosts(companyId: string) {
    return socialPosts.filter((p) => p.company_id === companyId);
  },
  getSocialMetrics(companyId: string) {
    return socialMetrics.filter((m) => m.company_id === companyId);
  },
  getCalls(companyId: string) {
    return calls.filter((c) => c.company_id === companyId);
  },
};
